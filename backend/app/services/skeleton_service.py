async def generate_skeleton(file_path: str, content: str) -> str:
    """Generate a logical skeleton with security layers applied."""
    language = detect_language(file_path) or "unknown"
    lang_context = get_language_prompt_context(language)

    # Layer 1+2: Strip comments and wrap in XML delimiters
    secured_code = prepare_secure_input(content, file_path, language)

    prompt = f"""Language Context: {lang_context}

File: {file_path}

{secured_code}

Generate the Logical Skeleton for this code. Preserve core logic, remove mechanical bloat.
Output ONLY valid code."""

    # System prompt includes security preamble
    system = SHIELDED_SYSTEM_PREAMBLE + "\n\n" + SKELETON_SYSTEM_PROMPT
    if is_expert_language(language):
        system += f"\n\nYou are an expert in {language}. Apply deep language-specific knowledge."

    skeleton = await llm_service.generate(
        prompt=prompt,
        task_type=TaskType.MAPPING,
        system_prompt=system,
        temperature=0.2,
    )

    # Layer 3: Sentinel validation on output
    verdict, explanation = await sentinel_validate(
        skeleton, context=f"Skeleton for {file_path}", use_llm=False  # Static-only for speed
    )
    if verdict == SentinelVerdict.BLOCKED:
        logger.warning(f"Sentinel blocked skeleton for {file_path}: {explanation}")
        return f"// SECURITY: Skeleton generation blocked by Sentinel.\n// Reason: {explanation}\n// Original code preserved for manual review."

    return skeleton


async def filter_triage_files(file_list: list[str]) -> tuple[list[str], list[str]]:
    """Triage pass: Split files into Keep vs Discard based on paths."""
    prompt = "Categorize these files:\n" + "\n".join(file_list)
    
    try:
        result = await llm_service.generate(
            prompt=prompt,
            task_type=TaskType.TRIAGE,
            system_prompt=TRIAGE_SYSTEM_PROMPT,
            temperature=0.0
        )
        
        # Clean markdown
        result = result.strip()
        if result.startswith("```"):
            result = result.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
            
        result = _clean_json_string(result)
        data = json.loads(result)
        return data.get("keep", []), data.get("discard", [])
    except Exception as e:
        logger.error(f"Triage failed, failing open (keeping all): {e}")
        return file_list, []


async def generate_batch_skeletons(file_batch: list[dict]) -> list[dict]:
    """Batch Map pass: Extract skeletons and summaries for multiple files in one LLM call."""
    prompt = "Analyze the following batch of files:\n\n"
    for item in file_batch:
        prompt += f"=== FILE: {item['path']} ===\n{item['content']}\n\n"
        
    try:
        result = await llm_service.generate(
            prompt=prompt,
            task_type=TaskType.MAPPING,
            system_prompt=BATCH_MAPPING_SYSTEM_PROMPT,
            temperature=0.2
        )
        
        result = result.strip()
        if result.startswith("```"):
            result = result.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
            
        result = _clean_json_string(result)
        return json.loads(result)
    except Exception as e:
        logger.error(f"Batch mapping failed: {e}")
        return []


async def generate_removal_log(file_path: str, original: str, skeleton: str) -> str:
    """Generate a JSON removal log comparing original to skeleton."""
    prompt = f"""File: {file_path}

=== ORIGINAL CODE ===
{original}

=== SKELETON CODE ===
{skeleton}

Generate the removal log as a JSON array."""

    result = await llm_service.generate(
        prompt=prompt,
        task_type=TaskType.MAPPING,
        system_prompt=REMOVAL_LOG_SYSTEM_PROMPT,
        temperature=0.1,
    )

    # Clean and validate JSON
    result = result.strip()
    if result.startswith("```"):
        result = result.split("\n", 1)[-1].rsplit("```", 1)[0].strip()

    result = _clean_json_string(result)

    try:
        json.loads(result)  # Validate it's valid JSON
        return result
    except json.JSONDecodeError:
        logger.warning(f"Invalid JSON in removal log for {file_path}, wrapping in array")
        return "[]"


