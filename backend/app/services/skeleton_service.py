def estimate_confidence(original: str, skeleton: str) -> float:
    """
    Estimate confidence score (0-100) based on reduction ratio and heuristics.
    Higher confidence = more certain that removal is correct.
    """
    orig_lines = len(original.strip().split("\n"))
    skel_lines = len(skeleton.strip().split("\n"))

    if orig_lines == 0:
        return 50.0

    reduction_ratio = 1 - (skel_lines / orig_lines)

    # Sweet spot: 20-60% reduction is most confident
    if 0.2 <= reduction_ratio <= 0.6:
        confidence = 85 + (reduction_ratio * 20)
    elif reduction_ratio < 0.2:
        # Very little removed — might be already clean
        confidence = 70 + (reduction_ratio * 50)
    elif reduction_ratio > 0.8:
        # Too much removed — might have lost important code
        confidence = max(40, 90 - (reduction_ratio * 60))
    else:
        confidence = 75 + (reduction_ratio * 15)

    return min(100.0, round(confidence, 1))
